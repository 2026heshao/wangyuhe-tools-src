def set_current(name: str):
    """切换当前主题；未知名称回退暗色。"""
    global _current
    _current = name if name in THEMES else "dark"


def get_current() -> str:
    return _current


def get() -> dict:
    """当前主题的配色字典。"""
    return THEMES.get(_current, THEMES["dark"])
